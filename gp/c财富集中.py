@lru_cache(maxsize=None)
def __init_财富集中度增长(target_col="top_1"):
    """
    将年度离散数据进行日度重采样并线性插值
    target_col 可选: 'top_10', 'top_1', 'top_01'
    """
    df = get_WID财富集中度数据()
    df["date"] = pd.to_datetime(df["date"], format="%Y%m%d")
    df.set_index("date", inplace=True)

    # 提取目标阶层的绝对占比数据
    df_target = df[[target_col]].copy()

    # 升频至“天(D)”并实施线性插值
    df_target = df_target.resample("D").asfreq()
    df_target[target_col] = df_target[target_col].interpolate(method="linear")

    # 统一时间索引为字符串 YYYYMMDD
    df_target.index = df_target.index.strftime("%Y%m%d").astype(int)

    df_target = df_target.loc[: int(datetime.now().strftime("%Y%m%d"))]
    return df_target


"""
    使用了很多种数据评估财定基财富集中倍率都太假了
    比如:基尼系数、劳动者报酬占GDP比例等等,得出的数据都是财富并没有集中
    给人第一反应就是 "稳中向好" [狗头]
    所以干脆生成一份,top_x财富集中增长率,乱用了
"""


def get_财富集中定基率(开始日期="20040101", 阶层="top_01"):
    """
    基于用户指定的开始日期，动态计算财富集中的定基增长倍率
    阶层参数可选:
        'top_10' -> 底层吊毛对抗中产+富豪整体
        'top_1'  -> 底层吊毛对抗资本阶层 (最符合体感)
        'top_01' -> 底层吊毛对抗超级大鳄
    """
    df = __init_财富集中度增长(target_col=阶层)

    # 获取指定开始日期当天的绝对份额基准值
    基准值 = df.loc[开始日期, 阶层]

    # 计算动态定基倍率
    df["temp_定基"] = df[阶层] / 基准值

    return df.loc[开始日期:]

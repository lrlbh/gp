跌幅 = 100
首次购买金额 = 5000
补仓阈值 = 0.90
print(
    f"首次持仓:{首次购买金额 / 1000 / 10:.2f}W\t",
    f"跌多少补仓库:{(1 - 0.9) * 100:.2f}%",
)
for i in range(9):
    跌幅 *= 补仓阈值
    首次购买金额 += 首次购买金额 * 补仓阈值
    print(
        f"第{i + 1}次补充仓  ",
        f"此时跌幅: {100 - 跌幅:05.2f}%  ",
        f"当前持仓: {首次购买金额 / 1000 / 10:.2f}W",
    )

